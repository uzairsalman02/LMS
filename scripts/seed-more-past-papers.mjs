async function seedMorePastPapers() {
  console.log(`Starting to seed ${samplePapers.length} past papers...`);

  const questions = await prisma.question.findMany({
    take: 10,
    orderBy: { createdAt: "desc" },
  });

  for (const paper of samplePapers) {
    const now = new Date();
    await prisma.pastPaper.upsert({
      where: { id: paper.id },
      update: {
        title: paper.title,
        year: paper.year,
        session: paper.session,
        paperType: paper.paperType,
        totalMarks: paper.totalMarks,
        durationMinutes: paper.durationMinutes,
        verificationStatus: paper.verificationStatus,
        updatedAt: now,
      },
      create: {
        id: paper.id,
        title: paper.title,
        year: paper.year,
        session: paper.session,
        paperType: paper.paperType,
        fileKey: paper.fileKey,
        fileUrl: paper.fileUrl,
        totalMarks: paper.totalMarks,
        durationMinutes: paper.durationMinutes,
        published: paper.published,
        verificationStatus: paper.verificationStatus,
        boardId: paper.boardId,
        classId: paper.classId,
        updatedAt: now,
      },
    });

    // Attach sample questions if not already attached
    for (let i = 0; i < Math.min(5, questions.length); i++) {
      const q = questions[i];
      const ppqId = `${paper.id}-q${i + 1}`;
      await prisma.pastPaperQuestion.upsert({
        where: {
          pastPaperId_questionId: {
            pastPaperId: paper.id,
            questionId: q.id,
          },
        },
        update: {
          updatedAt: now,
        },
        create: {
          id: ppqId,
          pastPaperId: paper.id,
          questionId: q.id,
          questionNumber: q.type === "MCQ" ? `Q1.${i + 1}` : `Q2.(${i + 1})`,
          section: q.type === "MCQ" ? "Section A - Objective (MCQs)" : "Section B - Subjective (Short Questions)",
          marks: q.marks || 1,
          updatedAt: now,
        },
      });
    }
  }

  console.log("Successfully seeded past papers and linked question records!");
}

seedMorePastPapers()
  .catch((e) => {
    console.error("Error seeding past papers:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
